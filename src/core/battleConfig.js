/**
 * Boss HP = 144 × 時長(分鐘) × regroupMarginRatio。
 *
 * 144 這個係數的意義：每分鐘 12 次攻擊機會 × 60% 專注率 × 20 傷害 = 144——
 * 這是「重整旗鼓完全不會發生」前提下的零安全邊際名目值，「達成 60% 專注率」
 * 在這個名目值上恰好等於「時限內打倒魔王」。但重整旗鼓（HP 歸零後 10 秒不能
 * 攻擊）在現實的持續性壞姿態下必然發生：60% 專注率依定義代表 40% 非端正時間，
 * 而 postureDamage 是不重置只暫停的累加器，長時間下必然累積到觸發重整旗鼓的
 * 門檻。若不打折，一個真的做到 60% 專注率的玩家會因為中途倒地幾次而打不倒
 * 魔王——遊戲對小孩的承諾就會落空。所以實際血量再乘上 `regroupMarginRatio`
 * 讓出安全邊際；`bossHpPerMinute` 本身維持 144 不動，邊際只施加在這一層。
 *
 * 注意這個承諾是有前提的：「60% 專注率就能在時限內打倒魔王」只在**沒有任何
 * 陷阱正式生效（trapCommitted）**的前提下成立。陷阱是明示的懲罰，而且給了
 * 20 秒撤銷視窗——那是刻意設計的逃生門，不是隱藏扣分，所以一次未撤銷的陷阱
 * 吃光整段邊際（實測 40 分鐘一次未撤銷的陷阱回血相當於 12.3 次攻擊，超過
 * 整個 +11 的邊際）是設計上就該有的代價，不是這個係數該吸收的東西——邊際只
 * 保證「維持 60% 專注率」這件事本身可以兌現，不保證「維持 60% 專注率但同時
 * 忽略陷阱警告」也能兌現。完整的承諾是「60% 專注率且沒有未撤銷的陷阱」。
 *
 * 展示模式時忽略 durationMs；一般模式時檢查 durationMs 必須是正有限數，
 * 否則拋錯。超出 5–40 分鐘範圍不會拋錯或 clamp（那是 UI 層的責任）。
 */
export function bossHpFor(durationMs, demoMode = false) {
  if (demoMode) return DEMO.bossHp

  // 檢查 durationMs 必須是正有限數
  if (!Number.isFinite(durationMs) || durationMs <= 0) {
    throw new Error(`bossHpFor: durationMs 必須是正有限數，收到 ${durationMs}`)
  }

  return Math.round(BATTLE.bossHpPerMinute * (durationMs / 60_000) * BATTLE.regroupMarginRatio)
}

export function attackIntervalFor(demoMode = false) {
  return demoMode ? DEMO.attackIntervalMs : BATTLE.attackIntervalMs
}

/**
 * 休息回合（Task 20）的門檻：這一輪真的坐了 ≥20 分鐘，下一輪開打之前先休息。
 *
 * 放在這個檔案而不是 StatsDashboard 或 App.vue 裡，是因為它有**兩個讀者**：
 * 結算頁那顆按鈕的**文字**（「休息一下再來」vs「再討伐一次」），以及按下去
 * 之後真正**做什麼**（enterBreak() vs startBattle()）。兩邊各自寫一次門檻，
 * 遲早會長出「按鈕寫著休息一下再來、按下去卻直接開打」這種分身，所以只准有
 * 一個函式回答這件事。
 */
export const BREAK_AFTER_MS = 20 * 60_000

/**
 * 這一輪結束後要不要先進休息回合。
 *
 * 展示模式一律回 false（spec：展示模式不觸發休息回合）——評審試玩 20 秒之後
 * 被請去休息三分鐘是很荒謬的畫面。durationMs 讀的是 SessionRecord 實際坐的
 * 時間（elapsedMs），不是使用者設定的時長：設 30 分鐘但兩分鐘就按結束的那一
 * 輪不需要休息。
 */
export function needsBreakAfter(record) {
  if (!record || record.demoMode) return false
  return (record.durationMs ?? 0) >= BREAK_AFTER_MS
}
